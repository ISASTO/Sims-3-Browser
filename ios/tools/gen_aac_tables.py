#!/usr/bin/env python3
"""Generate runtime/aac_tables.h (AAC-LC Huffman codebooks, scalefactor-band offsets, TNS limits).

The values are the normative tables of ISO/IEC 14496-3 (Huffman codebooks, Tables 4.A.1-4.A.12; scalefactor bands,
Tables 4.129-4.147; TNS_MAX_BANDS, Table 4.156). They are parsed from FFmpeg's libavcodec/aactab.c (LGPL-2.1+),
which transcribes them in specification index order:

    curl -o aactab.c https://raw.githubusercontent.com/FFmpeg/FFmpeg/n6.1/libavcodec/aactab.c
    python3 tools/gen_aac_tables.py aactab.c runtime/aac_tables.h
"""
import re, sys

src = open(sys.argv[1]).read()

def arr(name):
    m = re.search(r'\b' + re.escape(name) + r'\s*\[[^\]]*\]\s*=\s*\{(.*?)\};', src, re.S)
    if not m:
        raise SystemExit('missing table ' + name)
    body = re.sub(r'/\*.*?\*/|//[^\n]*', '', m.group(1), flags=re.S)
    return [int(v, 0) for v in re.findall(r'0x[0-9a-fA-F]+|\d+', body)]

out = ['/* aac_tables.h — generated by tools/gen_aac_tables.py from the ISO/IEC 14496-3 tables (see that script). */',
       '#pragma once', '#include <stdint.h>', '']

def emit(ctype, name, vals, per=12):
    out.append(f'static const {ctype} {name}[{len(vals)}] = {{')
    for i in range(0, len(vals), per):
        out.append('    ' + ', '.join(str(v) for v in vals[i:i + per]) + ',')
    out.append('};')

emit('uint32_t', 'aac_sf_code', arr('ff_aac_scalefactor_code'), 8)
emit('uint8_t', 'aac_sf_bits', arr('ff_aac_scalefactor_bits'))
sizes = [81, 81, 81, 81, 81, 81, 64, 64, 169, 169, 289]
for i in range(1, 12):
    c, b = arr(f'codes{i}'), arr(f'bits{i}')
    assert len(c) == len(b) == sizes[i - 1], (i, len(c), len(b))
    emit('uint16_t', f'aac_codes{i}', c)
    emit('uint8_t', f'aac_bits{i}', b)
out.append('static const uint16_t *const aac_spec_codes[11] = { ' + ', '.join(f'aac_codes{i}' for i in range(1, 12)) + ' };')
out.append('static const uint8_t *const aac_spec_bits[11] = { ' + ', '.join(f'aac_bits{i}' for i in range(1, 12)) + ' };')
out.append('static const uint16_t aac_spec_sizes[11] = { ' + ', '.join(map(str, sizes)) + ' };')

names_long = ['96', '96', '64', '48', '48', '32', '24', '24', '16', '16', '16', '8', '8']
names_short = ['96', '96', '96', '48', '48', '48', '24', '24', '16', '16', '16', '8', '8']
for n in sorted(set(names_long)):
    emit('uint16_t', f'aac_swb_1024_{n}', arr(f'swb_offset_1024_{n}'))
for n in sorted(set(names_short)):
    emit('uint16_t', f'aac_swb_128_{n}', arr(f'swb_offset_128_{n}'))
out.append('static const uint16_t *const aac_swb_1024[13] = { ' + ', '.join(f'aac_swb_1024_{n}' for n in names_long) + ' };')
out.append('static const uint16_t *const aac_swb_128[13] = { ' + ', '.join(f'aac_swb_128_{n}' for n in names_short) + ' };')
emit('uint8_t', 'aac_num_swb_1024', arr('ff_aac_num_swb_1024'), 13)
emit('uint8_t', 'aac_num_swb_128', arr('ff_aac_num_swb_128'), 13)
emit('uint8_t', 'aac_tns_max_bands_1024', arr('ff_tns_max_bands_1024'), 13)
emit('uint8_t', 'aac_tns_max_bands_128', arr('ff_tns_max_bands_128'), 13)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2])
