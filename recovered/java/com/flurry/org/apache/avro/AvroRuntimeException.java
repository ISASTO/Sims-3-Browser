package com.flurry.org.apache.avro;
public class AvroRuntimeException extends java.lang.RuntimeException {

    public AvroRuntimeException(String p1)
    {
        super(p1);
        return;
    }

    public AvroRuntimeException(String p1, Throwable p2)
    {
        super(p1, p2);
        return;
    }

    public AvroRuntimeException(Throwable p1)
    {
        super(p1);
        return;
    }
}
